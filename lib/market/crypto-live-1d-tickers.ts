/** Map Finsepa ticker → Binance USDT base (e.g. RNDR → RENDER). */
export function toBinanceUsdtBase(symbol: string): string {
  const base = normalizeCryptoBaseSymbol(symbol);
  if (!base) return "";
  return CRYPTO_BINANCE_BASE_ALIASES[base] ?? base;
}

/** Asset-page Binance last-trade allowlist (CMC-style header). */
export function usesBinanceLiveSpot(symbol: string): boolean {
  const base = normalizeCryptoBaseSymbol(symbol);
  if (!base) return false;
  const bases = cryptoBinanceLiveBases();
  return bases.includes(base) || bases.includes(toBinanceUsdtBase(base));
}

